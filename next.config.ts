import type { NextConfig } from 'next';

/**
 * Baseline hardening headers applied to every response.
 *
 * A Content-Security-Policy is intentionally omitted here: Next.js emits inline
 * bootstrap scripts, so a static CSP would require either `unsafe-inline` (which
 * defeats the policy) or nonce plumbing. Nonce-based CSP is tracked as a
 * hardening item rather than shipped as theatre that weakens itself.
 */
const securityHeaders = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  {
    key: 'Permissions-Policy',
    value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()',
  },
  { key: 'Cross-Origin-Opener-Policy', value: 'same-origin' },
  { key: 'X-DNS-Prefetch-Control', value: 'off' },
  {
    key: 'Strict-Transport-Security',
    value: 'max-age=63072000; includeSubDomains; preload',
  },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [{ source: '/:path*', headers: securityHeaders }];
  },
};

export default nextConfig;
